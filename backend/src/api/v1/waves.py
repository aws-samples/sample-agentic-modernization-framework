"""
Wave Planning API.
Reads the latest wave plan and moves apps between waves (plans are generated by
POST /workflow/wave-plan/generate).
"""

from __future__ import annotations

import logging

from boto3.dynamodb.conditions import Key
from fastapi import APIRouter

from backend.src.auth.rbac import Role, require_role
from backend.src.core.models import ApiResponse, generic_error_message
from backend.src.db.helpers import from_dynamo, get_table

logger = logging.getLogger(__name__)
router = APIRouter()


@router.get("/plan")
def get_wave_plan():
    """Get the latest wave plan."""
    try:
        table = get_table()
        resp = table.query(
            IndexName="GSI1",
            KeyConditionExpression=Key("GSI1PK").eq("TYPE#WAVE_PLAN"),
            ScanIndexForward=False,
            Limit=1,
        )
        items = from_dynamo(resp.get("Items", []))
        if not items:
            return ApiResponse(data=None, meta={"message": "No wave plan generated yet. Use POST /workflow/wave-plan/generate."})
        return ApiResponse(data=items[0])
    except Exception as exc:
        return ApiResponse(status="error", data={"message": generic_error_message(exc)})


@router.put("/assign", dependencies=[require_role(Role.ENGINEER)])
def assign_app_to_wave(app_id: str, wave_number: int):
    """Manually assign/move an app to a different wave."""
    try:
        table = get_table()
        table.update_item(
            Key={"PK": f"APP#{app_id}", "SK": "META"},
            UpdateExpression="SET wave_number = :w",
            ExpressionAttributeValues={":w": str(wave_number)},
        )
        return ApiResponse(data={"app_id": app_id, "wave_number": wave_number})
    except Exception as exc:
        return ApiResponse(status="error", data={"message": generic_error_message(exc)})
