# ── 1. requirements.txt ─────────────────────────────────────────────────────

def _dockerfile_pins(app_root: Path, repo: Path) -> dict[str, str]:
    pins: dict[str, str] = {}
    for d in (app_root, repo):
        df = d / "Dockerfile"
        if df.is_file():
            for m in re.finditer(r"([A-Za-z0-9_.-]+)==([\w.]+)", _read(df)):
                pins.setdefault(m.group(1).lower(), m.group(2))
    return pins


def generate_requirements(app_root: Path, repo: Path, wiring: dict) -> str | None:
    """requirements.txt text for the app's runtime imports, or None if nothing to write."""
    if (app_root / "requirements.txt").exists():
        return None
    imports = third_party_imports(app_root)
    lambda_only = bool(wiring.get("lambda_handler")) and not wiring.get("framework")
    if lambda_only:
        imports -= _SKIP_FOR_LAMBDA
    dists = sorted({IMPORT_TO_DIST.get(n, n) for n in imports} - _TEST_DEPS, key=str.lower)
    if not dists:
        return None
    pins = _dockerfile_pins(app_root, repo)
    lines = [f"{d}=={pins[d.lower()]}" if d.lower() in pins else d for d in dists]
    return "# Generated by AMF ci-fix from the app's imports — review and pin versions.\n" + "\n".join(lines) + "\n"


