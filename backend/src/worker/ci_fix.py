def scaffold_tests(repo: Path, app_root: Path, wiring: dict) -> Path | None:
    """Write tests/test_amf_smoke.py for a web app or Lambda handler; None if neither is known."""
    target = app_root / "tests" / _SMOKE_FILE
    if target.exists():
        return None
    if wiring.get("web_app"):
        routes = sorted({r for r in [wiring.get("health_check_path") or "/"]})
        text = _web_smoke(repo, app_root, wiring, routes)
    elif wiring.get("lambda_handler") and "." in wiring["lambda_handler"]:
        text = _lambda_smoke(app_root, wiring)
    else:
        return None
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text)
    return target


def prune_failing_smoke_tests(smoke: Path, failed_ids: list[str]) -> list[str]:
    """Drop failing scaffolded test functions; delete the file if none remain."""
    text = smoke.read_text()
    removed = []
    for tid in failed_ids:
        name = tid.split("::")[-1]
        pattern = re.compile(rf"\n\n\ndef {re.escape(name)}\(\):\n(?:    .*\n|\n)*?(?=\n\ndef |\Z)")
        new = pattern.sub("\n", text)
        if new != text:
            removed.append(name)
            text = new
    if not re.search(r"^def test_", text, re.M):
        smoke.unlink()
    else:
        smoke.write_text(text.rstrip("\n") + "\n")
    return removed


# ── 3. pytest.ini ───────────────────────────────────────────────────────────

def write_pytest_ini(app_root: Path) -> str | None:
    """pytest.ini so `coverage run -m pytest` collects and imports every test (None = not needed)."""
    ours = app_root / "pytest.ini"
    regenerate = ours.is_file() and _read(ours).startswith("# Generated by AMF ci-fix.")
    if regenerate:
        ours.unlink()  # AMF's own file: recompute (a later scaffold adds tests/)
    cfg = pytest_config(app_root)
    tests = test_files(app_root)
    if not tests:
        return None
    paths = missing_pythonpath(app_root, tests, cfg)
    uncollected = [t for t in tests if not re.match(r"^(test_.*|.*_test)\.py$", t.name)]
    if not paths and not uncollected and not regenerate:
        return None
    if cfg is not None:
        return f"SKIP: pytest config lives in {cfg['file']} — add pythonpath={paths} / python_files manually"
    testpaths = sorted({t.parent.relative_to(app_root).as_posix() for t in tests})
    lines = ["[pytest]"]
    if paths:
        lines.append("pythonpath = " + " ".join(paths))
    lines.append("testpaths = " + " ".join(testpaths))
    lines.append("python_files = test_*.py *_test.py test.py tests.py")
    (app_root / "pytest.ini").write_text("# Generated by AMF ci-fix.\n" + "\n".join(lines) + "\n")
    return "pytest.ini: " + "; ".join(lines[1:])


# ── 4. Dockerfile ───────────────────────────────────────────────────────────

def _stages(text: str) -> list[dict] | None:
    stages: list[dict] = []
    for raw in text.splitlines():
        ln = raw.strip()
        if not ln or ln.startswith("#"):
            continue
        instr = ln.split(None, 1)[0].upper()
        if instr not in _ALLOWED_INSTR or ln.endswith("\\"):
            return None
        if instr == "FROM":
            m = re.match(r"FROM\s+(\S+)(?:\s+AS\s+(\S+))?\s*$", ln, re.I)
            if not m:
                return None
            stages.append({"image": m.group(1), "name": (m.group(2) or "").lower(), "lines": [], "workdir": "/"})
        elif not stages:
            if instr != "ARG":
                return None
        else:
            if instr == "WORKDIR":
                wd = ln.split(None, 1)[1].strip()
                stages[-1]["workdir"] = wd if wd.startswith("/") else (stages[-1]["workdir"].rstrip("/") + "/" + wd)
            stages[-1]["lines"].append(ln)
    return stages or None


def rewrite_dockerfile(app_root: Path) -> tuple[str | None, str]:
    """(new Dockerfile text, note) for a simple Python Dockerfile; (None, reason) to leave it."""
    df = app_root / "Dockerfile"
    if not df.is_file():
        return None, "no Dockerfile in build_dir"
    if not (app_root / "requirements.txt").is_file():
        return None, "Dockerfile left as is: no requirements.txt to install the runtime deps from"
    stages = _stages(_read(df))
    if not stages:
        return None, "Dockerfile left as is: not a simple single-line-instruction Dockerfile"
    if not all(re.search(r"(?:^|/)python:", s["image"]) for s in stages):
        return None, "Dockerfile left as is: not every stage is a python image"
    final = stages[-1]
    image = final["image"]
    prefix, tag = image.rsplit("python:", 1)
    version = re.match(r"(\d+\.\d+)", tag)
    ver = "3.12" if (not version or _EOL_TAG.match(tag)) else version.group(1)
    base = f"{prefix}python:{ver}-slim"
    by_name = {s["name"]: s for s in stages if s["name"]}
    test_deps: set[str] = set()
    for s in stages:
        for ln in s["lines"]:
            if re.match(r"RUN\b.*\bpip\d?\s+install\b", ln, re.I):
                test_deps |= {d for d in _TEST_DEPS if re.search(rf"(?<![\w-]){re.escape(d)}(?![\w-])", ln)}
    copies, runs, envs, tail, labels = [], [], [], [], []
    for ln in final["lines"]:
        instr = ln.split(None, 1)[0].upper()
        if instr == "COPY":
            m = re.match(r"COPY\s+--from=(\S+)\s+(\S+)\s+(\S+)\s*$", ln, re.I)
            if m:
                src_stage, src = by_name.get(m.group(1).lower()), m.group(2)
                if re.search(r"site-packages|\.local|/usr/local/lib", src):
                    continue  # deps are reinstalled from requirements.txt
                if not src_stage:
                    return None, f"Dockerfile left as is: COPY --from={m.group(1)} of an unknown stage"
                wd = src_stage["workdir"].rstrip("/") or "/"
                norm = "/" + src.lstrip("./").rstrip("/") if not src.startswith("/") else src.rstrip("/")
                if norm.rstrip("/") not in (wd, wd.rstrip("/")):
                    return None, f"Dockerfile left as is: COPY --from={m.group(1)} {src} is not that stage's workdir"
                ctx = [c for c in src_stage["lines"] if c.upper().startswith("COPY ") and "--from" not in c.lower()]
                copies += [c for c in ctx if "requirements" not in c]
            elif "requirements" not in ln:
                copies.append(ln)
        elif instr == "RUN":
            if not re.search(r"\bpip\d?\s+install\b|pytest", ln):
                runs.append(ln)
        elif instr == "ENV":
            if ".local" not in ln:
                envs.append(ln)
        elif instr in ("EXPOSE", "CMD", "ENTRYPOINT"):
            tail.append(ln)
        elif instr == "LABEL":
            labels.append(ln)
    if not any(t.upper().startswith(("CMD", "ENTRYPOINT")) for t in tail):
        return None, "Dockerfile left as is: no CMD/ENTRYPOINT in the final stage"
    extra = " ".join(sorted(test_deps - {"pytest"}))
    out = [
        "# Rewritten by AMF ci-fix: tests run in a build stage; the runtime image carries only",
        "# requirements.txt deps and runs as a non-root user.",
        f"FROM {base} AS test",
        "WORKDIR /src",
        "COPY . .",
        f"RUN pip install --no-cache-dir -r requirements.txt pytest{(' ' + extra) if extra else ''} \\",
        "    && python -m pytest -q && touch /tmp/.amf-tests-passed",
        "",
        f"FROM {base} AS app",
        *labels,
        f"WORKDIR {final['workdir']}",
        "COPY requirements.txt /tmp/requirements.txt",
        "RUN pip install --no-cache-dir -r /tmp/requirements.txt && useradd --create-home --uid 10001 appuser",
        *runs,
        "COPY --from=test /tmp/.amf-tests-passed /tmp/.amf-tests-passed",
        *copies,
        *envs,
        "USER appuser",
        *tail,
    ]
    return "\n".join(out) + "\n", f"Dockerfile: multi-stage (tests in build stage), runtime deps only, " \
                                  f"non-root user, base {base}"


# ── 5. ruff --fix ───────────────────────────────────────────────────────────

# Ruff "unsafe" fixes that are mechanical for these codes (behaviour-preserving):
# F841 drops the unused `name =` binding and keeps the call (APP-MUSIC `resp = put_item(...)`).
_UNSAFE_ALLOWLIST = ("F841",)
# PLW1508 (non-str env default) has no autofix: `int(os.environ.get("PORT", 5000))` → "5000".
_INT_ENV_DEFAULT = re.compile(r"""(\b(?:int|float)\(\s*os\.(?:environ\.get|getenv)\(\s*(['"])\w+\2\s*,\s*)(\d+(?:\.\d+)?)(\s*\))""")


def fix_env_defaults(app_root: Path) -> int:
    """Quote numeric env-var defaults that are immediately converted with int()/float()."""
    from backend.src.worker.repo_scan import _files

    count = 0
    for f in _files(app_root, (".py",)):
        text = _read(f)
        new, n = _INT_ENV_DEFAULT.subn(lambda m: f"{m.group(1)}'{m.group(3)}'{m.group(4)}", text)
        if n:
            f.write_text(new)
            count += n
    return count


def ruff_fix(app_root: Path, runner: Runner) -> str | None:
    tools = _Tools(app_root, runner)
    if tools.error:
        return None
    env = sandbox_env(tools.venv)
    fixed = 0
    for extra in ([], ["--unsafe-fixes", "--select", ",".join(_UNSAFE_ALLOWLIST)]):
        r = runner([tools.bin("ruff"), "check", "--fix", "--exit-zero", *extra, "."], cwd=str(app_root), env=env)
        m = re.search(r"(\d+)\s+fixed", (r.stdout or "") + (r.stderr or ""))
        fixed += int(m.group(1)) if m else 0
    shutil.rmtree(tools.dir, ignore_errors=True)
    return f"ruff --fix: {fixed} fix(es) (safe + {', '.join(_UNSAFE_ALLOWLIST)})" if fixed else None


# ── orchestration ───────────────────────────────────────────────────────────

def _item(report: dict, name: str) -> dict:
    return next((i for i in report.get("items", []) if i["check"] == name), {})


def apply_fixes(repo: Path, build_dir: str, wiring: dict, before: dict, *, threshold: int,
                runner: Runner | None = None, run_tools: bool = True) -> tuple[list[str], list[str], dict]:
    """Apply the fixes in order; returns (changes, warnings, after-report)."""
    runner = runner or _default_runner
    app_root = repo / build_dir if build_dir else repo
    changes, warnings = [], []
    if (wiring.get("language") or "python") != "python":
        return [], [f"ci-fix supports Python only (language={wiring.get('language')})"], before

    req = generate_requirements(app_root, repo, wiring)
    if req:
        (app_root / "requirements.txt").write_text(req)
        changes.append("requirements.txt generated from imports: "
                       + ", ".join(ln for ln in req.splitlines() if ln and not ln.startswith("#")))

    smoke = None
    cov = before.get("coverage_pct")
    if before.get("tests_found", 0) == 0 or (cov is not None and cov < threshold):
        smoke = scaffold_tests(repo, app_root, wiring)
        if smoke:
            changes.append(f"scaffolded smoke tests: {smoke.relative_to(repo).as_posix()}")
        elif before.get("tests_found", 0) == 0:
            warnings.append("no tests and no detectable web app / Lambda handler to scaffold smoke tests for")

    ini = write_pytest_ini(app_root)
    if ini and ini.startswith("SKIP:"):
        warnings.append(ini[5:].strip())
    elif ini:
        changes.append(ini)

    if _item(before, "dockerfile").get("status") == "fixable":
        text, note = rewrite_dockerfile(app_root)
        if text:
            (app_root / "Dockerfile").write_text(text)
            changes.append(note)
        else:
            warnings.append(note)

    n = fix_env_defaults(app_root)
    if n:
        changes.append(f"quoted {n} numeric env-var default(s) passed to int()/float() (ruff PLW1508)")

    after = check(repo, build_dir, wiring, threshold=threshold, run_tools=run_tools, runner=runner)
    # Coverage is only known once the tests are collectable: scaffold now if still short.
    if (not smoke and after.get("coverage_pct") is not None and after["coverage_pct"] < threshold):
        smoke = scaffold_tests(repo, app_root, wiring)
        if smoke:
            changes.append(f"scaffolded smoke tests: {smoke.relative_to(repo).as_posix()}")
            ini = write_pytest_ini(app_root)
            if ini and not ini.startswith("SKIP:"):
                changes = [c for c in changes if not c.startswith("pytest.ini:")] + [ini]
    if run_tools:
        note = ruff_fix(app_root, runner)
        if note:
            changes.append(note)
    after = check(repo, build_dir, wiring, threshold=threshold, run_tools=run_tools, runner=runner)
    tp = _item(after, "tests_pass")
    if smoke and smoke.exists() and tp.get("status") == "blocker":
        failed = re.findall(r"FAILED (\S*" + re.escape(_SMOKE_FILE) + r"::\w+)", tp.get("evidence", ""))
        if failed:
            removed = prune_failing_smoke_tests(smoke, failed)
            warnings.append("scaffolded smoke test(s) failed and were removed: " + ", ".join(removed)
                            + " — the app/handler likely mishandles that input:\n" + tp["evidence"][-600:])
            after = check(repo, build_dir, wiring, threshold=threshold, run_tools=run_tools, runner=runner)
    if after.get("coverage_pct") is not None and after["coverage_pct"] < threshold:
        warnings.append(f"coverage {after['coverage_pct']:.0f}% is still under the {threshold}% gate")
    if after.get("status") == "blocked":
        warnings += [f"{i['check']}: {i['evidence'][:300]}" for i in after["items"] if i["status"] == "blocker"]
    return changes, warnings, after


def _git(repo: Path, *args: str) -> subprocess.CompletedProcess:
    return run_git([*args], cwd=str(repo), capture_output=True, text=True, check=False)


# Byproducts of running the checks (pytest/coverage/ruff) in the clone — never commit them.
_ARTIFACT_PATHSPECS = (":(exclude,glob)**/__pycache__/**", ":(exclude,glob)**/*.pyc", ":(exclude,glob)**/.coverage",
                       ":(exclude,glob)**/.coverage.*", ":(exclude,glob)**/coverage.xml", ":(exclude,glob)**/htmlcov/**",
                       ":(exclude,glob)**/.pytest_cache/**", ":(exclude,glob)**/.ruff_cache/**", ":(exclude,glob)**/.venv/**")


def commit_and_push(repo: Path, branch: str, changes: list[str]) -> str:
    """'committed' / 'no_change' / 'push_failed: …'."""
    _git(repo, "add", "-A", "--", ".", *_ARTIFACT_PATHSPECS)
    if _git(repo, "diff", "--cached", "--quiet").returncode == 0:
        return "no_change"
    msg = "chore(ci): AMF CI-readiness fixes\n\n" + "\n".join(f"- {c}" for c in changes)
    r = _git(repo, "commit", "-m", msg)
    if r.returncode != 0:
        return f"commit_failed: {r.stderr.strip()[:300]}"
    r = _git(repo, "push", "origin", branch)
    if r.returncode != 0:
        r = _git(repo, "push", "origin", f"HEAD:{branch}")
    return "committed" if r.returncode == 0 else f"push_failed: {r.stderr.strip()[:300]}"


def _primary_repo(app: dict) -> dict:
    repos = [r for r in app.get("repos") or [] if str(r.get("url") or "").strip()]
    repos.sort(key=lambda r: 0 if "codecommit" in str(r.get("url")) or r.get("provider") == "codecommit" else 1)
    return repos[0] if repos else {}


