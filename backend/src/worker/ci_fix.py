"""MODE=ci-fix — bring the app's build/test files up to the CI gates (spec 14).

Runs on the app's migration branch after the transforms, before CI/CD is
generated. It changes ONLY build and test files — never application logic
(ruff's safe fixes are the one exception, they're mechanical):

  1. requirements.txt from the app's third-party imports (pins from Dockerfile pip lines)
  2. scaffolded smoke tests when there are none / coverage is under the threshold
  3. pytest.ini (pythonpath / testpaths / python_files) when pytest wouldn't collect or import the tests
  4. a multi-stage Dockerfile for simple Python Dockerfiles: tests in a build stage, runtime image
     with only requirements.txt deps, non-root user, non-EOL base
  5. `ruff check --fix` (safe fixes only)

The readiness check runs before and after; a scaffolded test that fails is pruned
(its failure is reported — it usually points at a real handler bug). The result
is advisory for Execution: tool failures still call back SendTaskSuccess with
status=error; only an unexpected crash sends SendTaskFailure.

Python only (Java next iteration: add `_fix_java` and dispatch on language).
"""

